// Writes src/lib/media/image-manifest.ts: every image in public/images/media/
// with its pixel size. Runs before `next dev` and `next build` (predev /
// prebuild), so /admin's image picker and the public read layer know the repo's
// images without touching the filesystem at request time, and next/image gets
// the width and height a runtime filename can't give it.
//
// sharp comes with Next (an optional dependency of `next`).

import { readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import sharp from 'sharp';

const root = path.resolve(import.meta.dirname, '..');
const dir = path.join(root, 'public', 'images', 'media');
const out = path.join(root, 'src', 'lib', 'media', 'image-manifest.ts');

// Mirrors the DB's media_item_image_file_format check.
const FILE_PATTERN = /^[a-z0-9][a-z0-9._-]*\.(png|jpe?g|webp|gif)$/;

const names = (await readdir(dir).catch(() => []))
  .filter((name) => !name.startsWith('.'))
  .sort();

const entries = [];
for (const name of names) {
  if (!FILE_PATTERN.test(name)) {
    console.warn(
      `media-manifest: skipping ${name} (lowercase a-z, 0-9, ".", "_", "-"; png/jpg/webp/gif)`,
    );
    continue;
  }
  const { width, height } = await sharp(path.join(dir, name)).metadata();
  entries.push(`  '${name}': { width: ${width}, height: ${height} },`);
}

const source = `// GENERATED by scripts/media-manifest.mjs (predev / prebuild). Do not edit.

export interface ManifestImage {
  width: number;
  height: number;
}

export const imageManifest: Record<string, ManifestImage> = {${
  entries.length ? `\n${entries.join('\n')}\n` : ''
}};
`;

await writeFile(out, source);
console.log(`media-manifest: ${entries.length} image(s)`);
